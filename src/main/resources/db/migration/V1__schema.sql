-- =====================================================================
-- Delícia Caseira da Elaine — esquema inicial (PostgreSQL)
-- Compatível também com H2 em MODE=PostgreSQL (usado nos testes).
-- Regras de negócio críticas são garantidas também no banco (CHECK),
-- não apenas na aplicação.
-- =====================================================================

-- Administradora (herda "nome" de Pessoa). Senha guardada SOMENTE como hash BCrypt.
CREATE TABLE administradora (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(100) NOT NULL,
    usuario     VARCHAR(50)  NOT NULL,
    senha_hash  VARCHAR(100) NOT NULL,
    criado_em   TIMESTAMP    NOT NULL,
    CONSTRAINT uk_administradora_usuario UNIQUE (usuario)
);

-- Cliente (herda "nome" de Pessoa). Identificado pelo telefone/WhatsApp.
-- Endereço é opcional (Regra 4: retirada não exige endereço).
CREATE TABLE cliente (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome               VARCHAR(100) NOT NULL,
    telefone           VARCHAR(11)  NOT NULL,
    endereco           VARCHAR(255),
    cliente_frequente  BOOLEAN      NOT NULL DEFAULT FALSE,
    criado_em          TIMESTAMP    NOT NULL,
    CONSTRAINT uk_cliente_telefone UNIQUE (telefone)
);

-- Produto: cada sabor/variedade é um produto (RF22, RF23).
CREATE TABLE produto (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(100)  NOT NULL,
    preco      NUMERIC(10,2) NOT NULL,
    foto       VARCHAR(100),
    descricao  VARCHAR(500),
    ativo      BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_produto_nome UNIQUE (nome),
    CONSTRAINT ck_produto_preco CHECK (preco > 0)
);

-- Pedido
CREATE TABLE pedido (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo                    VARCHAR(8)   NOT NULL,
    cliente_id                BIGINT       NOT NULL,
    data_pedido               DATE         NOT NULL,
    horario_pedido            TIME         NOT NULL,
    data_entrega_retirada     DATE         NOT NULL,
    horario_entrega_retirada  TIME,
    status                    VARCHAR(20)  NOT NULL DEFAULT 'PENDENTE',
    tipo_entrega              VARCHAR(20)  NOT NULL,
    endereco_entrega          VARCHAR(255),
    forma_pagamento           VARCHAR(20),
    origem                    VARCHAR(20)  NOT NULL,
    observacoes               VARCHAR(500),
    criado_em                 TIMESTAMP    NOT NULL,
    CONSTRAINT uk_pedido_codigo UNIQUE (codigo),
    CONSTRAINT fk_pedido_cliente FOREIGN KEY (cliente_id) REFERENCES cliente (id),
    -- Regra 7: apenas Pendente, Concluído e Cancelado
    CONSTRAINT ck_pedido_status CHECK (status IN ('PENDENTE', 'CONCLUIDO', 'CANCELADO')),
    CONSTRAINT ck_pedido_tipo_entrega CHECK (tipo_entrega IN ('RETIRADA', 'ENTREGA')),
    CONSTRAINT ck_pedido_forma_pagamento CHECK (forma_pagamento IS NULL OR forma_pagamento IN ('PIX', 'CARTAO', 'DINHEIRO')),
    CONSTRAINT ck_pedido_origem CHECK (origem IN ('SITE', 'WHATSAPP', 'PRESENCIAL')),
    -- Regra 3: entrega exige endereço
    CONSTRAINT ck_pedido_endereco_entrega CHECK (
        tipo_entrega <> 'ENTREGA' OR (endereco_entrega IS NOT NULL AND LENGTH(TRIM(endereco_entrega)) > 0)
    ),
    CONSTRAINT ck_pedido_datas CHECK (data_entrega_retirada >= data_pedido)
);
CREATE INDEX ix_pedido_data_entrega ON pedido (data_entrega_retirada);
CREATE INDEX ix_pedido_cliente ON pedido (cliente_id);
CREATE INDEX ix_pedido_status ON pedido (status);

-- Item do pedido (composição): guarda o preço unitário do momento da venda.
CREATE TABLE item_pedido (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id       BIGINT        NOT NULL,
    produto_id      BIGINT        NOT NULL,
    quantidade      INTEGER       NOT NULL,
    preco_unitario  NUMERIC(10,2) NOT NULL,
    CONSTRAINT fk_item_pedido_pedido FOREIGN KEY (pedido_id) REFERENCES pedido (id) ON DELETE CASCADE,
    CONSTRAINT fk_item_pedido_produto FOREIGN KEY (produto_id) REFERENCES produto (id),
    CONSTRAINT ck_item_pedido_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_item_pedido_preco CHECK (preco_unitario >= 0)
);
CREATE INDEX ix_item_pedido_pedido ON item_pedido (pedido_id);
CREATE INDEX ix_item_pedido_produto ON item_pedido (produto_id);

-- Pagamento: 0..1 por pedido (UNIQUE em pedido_id impede duplicidade).
CREATE TABLE pagamento (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id       BIGINT        NOT NULL,
    tipo            VARCHAR(20)   NOT NULL,
    valor           NUMERIC(10,2) NOT NULL,
    data_pagamento  DATE          NOT NULL,
    criado_em       TIMESTAMP     NOT NULL,
    CONSTRAINT uk_pagamento_pedido UNIQUE (pedido_id),
    CONSTRAINT fk_pagamento_pedido FOREIGN KEY (pedido_id) REFERENCES pedido (id),
    CONSTRAINT ck_pagamento_tipo CHECK (tipo IN ('PIX', 'CARTAO', 'DINHEIRO')),
    CONSTRAINT ck_pagamento_valor CHECK (valor > 0)
);

-- Registro financeiro: somente ENTRADAS (despesas e lucro não são modelados).
-- pagamento_id preenchido = entrada automática gerada pelo pagamento (no máximo uma).
-- pagamento_id nulo       = entrada manual avulsa da administradora.
CREATE TABLE registro_financeiro (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    valor          NUMERIC(10,2) NOT NULL,
    data_registro  DATE          NOT NULL,
    descricao      VARCHAR(200)  NOT NULL,
    pagamento_id   BIGINT,
    criado_em      TIMESTAMP     NOT NULL,
    CONSTRAINT uk_registro_financeiro_pagamento UNIQUE (pagamento_id),
    CONSTRAINT fk_registro_financeiro_pagamento FOREIGN KEY (pagamento_id) REFERENCES pagamento (id),
    CONSTRAINT ck_registro_financeiro_valor CHECK (valor > 0)
);
CREATE INDEX ix_registro_financeiro_data ON registro_financeiro (data_registro);

-- Item de estoque = INSUMO do negócio (farinha, leite, ovos...), controle manual.
CREATE TABLE item_estoque (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome               VARCHAR(100)  NOT NULL,
    quantidade_atual   NUMERIC(12,3) NOT NULL,
    unidade_medida     VARCHAR(20)   NOT NULL,
    quantidade_minima  NUMERIC(12,3) NOT NULL,
    CONSTRAINT uk_item_estoque_nome UNIQUE (nome),
    CONSTRAINT ck_item_estoque_unidade CHECK (unidade_medida IN ('KG', 'G', 'LITRO', 'ML', 'UNIDADE', 'DUZIA', 'PACOTE')),
    CONSTRAINT ck_item_estoque_atual CHECK (quantidade_atual >= 0),
    CONSTRAINT ck_item_estoque_minima CHECK (quantidade_minima >= 0)
);
